//! How a failing test tells `cargo handoff` that a regeneration fixes it.
//!
//! # The polarity
//!
//! **A failure is unfixable unless the test that failed says otherwise.** The gate
//! used to work the other way round: it recognised the failures it could *not*
//! fix by pattern (`compile failed:`, `memory leak`, …) and treated the rest as
//! staleness. That made every new kind of failure fixable by default, and a
//! failure whose message happened to look like staleness — a leak naming
//! `fill_expected` as the command to run, a test comparing a live report against
//! a pinned one — either slipped through as a green gate or stopped it for want
//! of a pattern. A list of what *cannot* be fixed has to be complete to be safe;
//! a list of what *can* only has to be honest.
//!
//! So the test that knows why it failed is the one that says what fixes it, by
//! printing a [`Fill`] on a line of its own. A test that prints none is stuck, and
//! the gate stops on it and names it.
//!
//! # The line
//!
//! ```text
//! handoff-fill: <kind>\t<field>\t<field>…
//! ```
//!
//! One line per thing to fix, anywhere in the test's output (a panic message
//! included), tab-separated so a field may hold any text without a newline or a
//! tab. [`Fill::marker`] writes it and [`Fill::parse`] reads it; each kind and its
//! fields are listed on [`Fill`].
//!
//! A line that starts with the prefix but does not parse is an error, not
//! nothing: the writer and the reader disagreeing is exactly the case that must
//! not read as "no remedy asked for" or, worse, as one.

/// What every marker line starts with.
pub const PREFIX: &str = "handoff-fill: ";

/// One thing a regeneration can fix, as a failing test reports it.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub enum Fill {
    /// A recorded section of a case no longer says what the case does.
    /// Refilled from the actual output by `fill_expected`, scoped to `case`.
    ///
    /// Fields: `case` (the display path `AIPL_CASE` matches), `section` (the
    /// section's name as the harness spells it: `stdout`, `report`,
    /// `expect file: out.txt`, …).
    Section { case: String, section: String },
    /// Cases exist that the checked-in per-case `#[test]` list does not name (or
    /// it names ones that are gone). Regenerated by `fill_case_tests`; each case
    /// in `added` has never run, so it also needs its sections filled.
    ///
    /// Fields: one per added case, none when the list only has stale entries.
    CaseTests { added: Vec<String> },
    /// A case's row in `tests/performance_metrics.md` disagrees with its run.
    /// Rewritten by `refresh_perfmon`, and listed for review: the move may be the
    /// regression the table exists to catch.
    ///
    /// Fields: `case`, then one line per metric that moved.
    BaselineMoved { case: String, moves: Vec<String> },
    /// A case has no row in `tests/performance_metrics.md`. Fields: `case`.
    BaselineMissing { case: String },
    /// The checked-in dogfood artifact no longer matches the sources it was built
    /// from. Regenerated through the staged-IR flow. No fields.
    Ir,
    /// The checked-in documentation site no longer matches the source it
    /// documents. Regenerated by `fill_docs`. No fields.
    Docs,
    /// A project's checked-in compiler is not built from this repository's
    /// current sources. Re-copied by `fill_project_compilers`. No fields.
    Compilers,
}

impl Fill {
    /// The line a test prints to ask for this, without a trailing newline.
    ///
    /// A field is written as given, except that a tab or newline in it — which
    /// would end the field or the line — becomes a space.
    pub fn marker(&self) -> String {
        let (kind, fields): (&str, Vec<&str>) = match self {
            Fill::Section { case, section } => ("section", vec![case, section]),
            Fill::CaseTests { added } => ("case-tests", added.iter().map(String::as_str).collect()),
            Fill::BaselineMoved { case, moves } => (
                "baseline-moved",
                std::iter::once(case.as_str())
                    .chain(moves.iter().map(String::as_str))
                    .collect(),
            ),
            Fill::BaselineMissing { case } => ("baseline-missing", vec![case]),
            Fill::Ir => ("ir", vec![]),
            Fill::Docs => ("docs", vec![]),
            Fill::Compilers => ("compilers", vec![]),
        };
        let mut line = format!("{PREFIX}{kind}");
        for field in fields {
            line.push('\t');
            line.extend(field.chars().map(|c| {
                if matches!(c, '\t' | '\n' | '\r') {
                    ' '
                } else {
                    c
                }
            }));
        }
        line
    }

    /// Read one line of a test's output: `None` if it is not a marker at all,
    /// `Some(Err(why))` if it starts like one and is not a valid one.
    pub fn parse(line: &str) -> Option<Result<Fill, String>> {
        let rest = line.trim_end().strip_prefix(PREFIX)?;
        let mut fields = rest.split('\t');
        let kind = fields.next().unwrap_or_default();
        let fields: Vec<String> = fields.map(str::to_string).collect();
        let bad = |why: &str| Some(Err(format!("`{kind}`: {why} (in `{}`)", line.trim_end())));
        Some(Ok(match (kind, fields.as_slice()) {
            ("section", [case, section]) => Fill::Section {
                case: case.clone(),
                section: section.clone(),
            },
            ("section", _) => return bad("expected a case and a section"),
            ("case-tests", added) => Fill::CaseTests {
                added: added.to_vec(),
            },
            ("baseline-moved", [case, moves @ ..]) => Fill::BaselineMoved {
                case: case.clone(),
                moves: moves.to_vec(),
            },
            ("baseline-moved", _) => return bad("expected a case"),
            ("baseline-missing", [case]) => Fill::BaselineMissing { case: case.clone() },
            ("baseline-missing", _) => return bad("expected exactly a case"),
            ("ir", []) => Fill::Ir,
            ("docs", []) => Fill::Docs,
            ("compilers", []) => Fill::Compilers,
            ("ir" | "docs" | "compilers", _) => return bad("takes no fields"),
            _ => return bad("unknown kind"),
        }))
    }

    /// Every marker in `output`, in order, with the lines that failed to parse.
    pub fn scan(output: &str) -> (Vec<Fill>, Vec<String>) {
        let mut fills = Vec::new();
        let mut errors = Vec::new();
        for parsed in output.lines().filter_map(Fill::parse) {
            match parsed {
                Ok(fill) => fills.push(fill),
                Err(why) => errors.push(why),
            }
        }
        (fills, errors)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// One of each kind, with the awkward shapes: no fields, many, text with
    /// punctuation.
    fn all() -> Vec<Fill> {
        vec![
            Fill::Section {
                case: "cases/x/y.aipl".into(),
                section: "expect file: out.txt".into(),
            },
            Fill::CaseTests { added: vec![] },
            Fill::CaseTests {
                added: vec!["cases/a/b".into(), "cases/a/c".into()],
            },
            Fill::BaselineMoved {
                case: "cases/x/y.aipl".into(),
                moves: vec![
                    "allocations: 3 -> 4 (+33.3%)".into(),
                    "instructions: 120 -> 130 (+8.3%)".into(),
                ],
            },
            Fill::BaselineMissing {
                case: "cases/new/one.aipl".into(),
            },
            Fill::Ir,
            Fill::Docs,
            Fill::Compilers,
        ]
    }

    #[test]
    fn every_kind_round_trips() {
        for fill in all() {
            assert_eq!(
                Fill::parse(&fill.marker()),
                Some(Ok(fill.clone())),
                "{fill:?}"
            );
        }
    }

    #[test]
    fn a_marker_is_found_among_other_output() {
        let output = format!(
            "thread 'x' panicked at tests/cases.rs:1:1:\n[cases/x]: `stdout` mismatch\n{}\nnote: run with `RUST_BACKTRACE=1`",
            Fill::Docs.marker()
        );
        assert_eq!(Fill::scan(&output), (vec![Fill::Docs], vec![]));
    }

    /// A line of ordinary text that mentions the prefix mid-line is prose, not a
    /// request: the marker owns its whole line.
    #[test]
    fn the_prefix_must_start_the_line() {
        assert_eq!(Fill::parse("see handoff-fill: ir for details"), None);
        assert_eq!(Fill::parse("nothing to see"), None);
    }

    #[test]
    fn a_line_that_starts_like_a_marker_but_is_not_one_is_an_error() {
        for line in [
            "handoff-fill: nonsense",
            "handoff-fill: section\tonly-a-case",
            "handoff-fill: ir\textra",
            "handoff-fill: baseline-missing",
        ] {
            assert!(
                matches!(Fill::parse(line), Some(Err(_))),
                "should be rejected: {line}"
            );
        }
        let (fills, errors) = Fill::scan("handoff-fill: nonsense\nhandoff-fill: ir");
        assert_eq!(fills, vec![Fill::Ir]);
        assert_eq!(errors.len(), 1);
    }

    #[test]
    fn a_tab_or_newline_in_a_field_cannot_break_the_line() {
        let marker = Fill::Section {
            case: "a\tb".into(),
            section: "c\nd".into(),
        }
        .marker();
        assert_eq!(marker.lines().count(), 1);
        assert_eq!(
            Fill::parse(&marker),
            Some(Ok(Fill::Section {
                case: "a b".into(),
                section: "c d".into()
            }))
        );
    }
}
